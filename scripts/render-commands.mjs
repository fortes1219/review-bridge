#!/usr/bin/env node
// Writes README.md's Commands section from the command table (review-bridge/router/index.mjs),
// with the same text `--help` prints. `--check` changes nothing and fails when the README is out
// of date, which is what CI runs.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { renderCommandHelp, renderMainHelp } from "../review-bridge/router/help.mjs";
import { COMMANDS } from "../review-bridge/router/index.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readmePath = path.join(root, "README.md");
const START = "<!-- commands:start -->";
const END = "<!-- commands:end -->";

function block(text) {
  return "```text\n" + text.trimEnd() + "\n```";
}

export function renderCommandsSection() {
  const names = (audience) => Object.keys(COMMANDS).filter((name) => COMMANDS[name].audience === audience);
  return [
    START,
    "<!-- Generated by scripts/render-commands.mjs from review-bridge/router/index.mjs; edit the table, not this section. -->",
    "",
    block(renderMainHelp()),
    "",
    ...names("human").flatMap((name) => ["### " + name, "", block(renderCommandHelp(name)), ""]),
    "### For agents and scripts",
    "",
    "Shown by `review-bridge --help --all`. `start` does what `work-plan` and `work-start` do in one command.",
    "",
    ...names("agent").flatMap((name) => ["#### " + name, "", block(renderCommandHelp(name, { all: true })), ""]),
    END,
  ].join("\n");
}

function rendered(readme) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error("README.md has no " + START + " ... " + END + " section.");
  // The section takes the README's own line endings (a Windows checkout may have CRLF).
  const eol = readme.includes("\r\n") ? "\r\n" : "\n";
  return readme.slice(0, start) + renderCommandsSection().replaceAll("\n", eol) + readme.slice(end + END.length);
}

const readme = fs.readFileSync(readmePath, "utf8");
const next = rendered(readme);
if (process.argv.includes("--check")) {
  if (next !== readme) {
    process.stderr.write("README.md's Commands section is out of date. Run: node scripts/render-commands.mjs\n");
    process.exitCode = 1;
  }
} else if (next !== readme) {
  fs.writeFileSync(readmePath, next);
  process.stdout.write("README.md: Commands section rewritten.\n");
}
